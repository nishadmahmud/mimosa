function byDateDesc(a, b) {
  return String(b.date).localeCompare(String(a.date));
}

export function getFeaturedPress() {
  return pressArticles.filter((a) => a.featured).sort(byDateDesc);
}

export function getPratidinColumns() {
  return pressArticles
    .filter((a) => a.outlet === "Bangladesh Pratidin")
    .sort(byDateDesc);
}

export function getDailyStarArticles() {
  return pressArticles
    .filter((a) => a.outlet === "The Daily Star")
    .sort(byDateDesc);
}

/** Homepage strip: newest Pratidin columns */
export function getHomepagePratidinStrip(limit = 6) {
  return getPratidinColumns().slice(0, limit);
}

export function getAllPressSorted() {
  return [...pressArticles].sort(byDateDesc);
}
